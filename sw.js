/* =====================================================================
   Cleo service worker (generated by source/build.js from sw.template.js).
   Caches the whole app on first visit so it opens with no internet,
   which the Terminal needs (SYS-01). Network first for the page and for
   content/*.md (so a new build, or an edit to content/plans.md, is picked up
   when online); cache first for fonts, icons and images.
   NOTE: service workers only run over https or on localhost; on localhost the app leaves
   this one off unless it is opened with ?offline (launcher.js), so previews stay live.
   BACKEND: never cache API responses here; the terminal's offline sales
   queue belongs in IndexedDB, uploaded by the app when the connection returns.
   ===================================================================== */
const CACHE = 'cleo-72cf15aa9f';
const FILES = [
  "landing.html",
  "index.html",
  "manifest.webmanifest",
  "content/plans.md",
  "legal/privacy.html",
  "legal/terms.html",
  "assets/brand/aeso-mark.png",
  "assets/brand/cleo-emblem.png",
  "assets/fonts/HelveticaNeueBold.otf",
  "assets/fonts/HelveticaNeueLight.otf",
  "assets/fonts/HelveticaNeueMedium.otf",
  "assets/fonts/HelveticaNeueRoman.otf",
  "assets/icons/phosphor/bold/Phosphor-Bold.woff",
  "assets/icons/phosphor/bold/Phosphor-Bold.woff2",
  "assets/icons/phosphor/bold/style.css",
  "assets/icons/phosphor/fill/Phosphor-Fill.woff",
  "assets/icons/phosphor/fill/Phosphor-Fill.woff2",
  "assets/icons/phosphor/fill/style.css",
  "assets/icons/phosphor/regular/Phosphor.woff",
  "assets/icons/phosphor/regular/Phosphor.woff2",
  "assets/icons/phosphor/regular/style.css",
  "assets/vendor/supabase-js-2.118.0.js",
  "assets/vendor/supabase-js-2.118.0.json",
  "assets/vendor/supabase-js-LICENSE.txt"
];

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('cleo-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  const requestURL = new URL(req.url);
  if (req.method !== 'GET' || requestURL.origin !== location.origin) return;
  // Authentication callbacks must never leave codes or token hashes in cache
  // request keys, or replay an old callback while offline.
  if (['code', 'token_hash', 'access_token', 'refresh_token', 'sb_flow_id', 'error', 'error_code', 'error_description', 'auth'].some((key) => requestURL.searchParams.has(key))) {
    e.respondWith(fetch(req)); return;
  }
  const isPage = req.mode === 'navigate' || req.destination === 'document';
  // hand-edited content: the newest copy when online, the cached one offline
  if (new URL(req.url).pathname.endsWith('.md')) {
    e.respondWith(fetch(req).then((res) => { if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); } return res; }).catch(() => caches.match(req, { ignoreSearch: true })));
    return;
  }
  if (isPage) {
    // Public home, landing and operational app never share a cache key. A host
    // may still return index.html at '/'; its entry guard redirects, and that
    // response must not overwrite either explicit page in the offline cache.
    const path = new URL(req.url).pathname;
    const home = path === new URL(self.registration.scope).pathname;
    const key = path.endsWith('/index.html') ? 'index.html' : path.endsWith('/landing.html') ? 'landing.html' : req;
    e.respondWith(fetch(req).then((res) => { if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(key, copy)); } return res; }).catch(async () => {
      const hit = await caches.match(key, { ignoreSearch: true });
      if (hit) return hit;
      if (home) return (await caches.match('landing.html')) || Response.error();
      return Response.error();
    }));
    return;
  }
  e.respondWith(caches.match(req).then((hit) => hit || fetch(req).then((res) => { if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); } return res; })));
});
